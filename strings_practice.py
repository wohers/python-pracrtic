# 2. Приведи к нижнему регистру и убери пробелы (.lower().strip()).
# 3. Разбей через .split().
# 4. Если слов нет — напечатай "Ты ничего не сказал."
# 5. Иначе достань действие (первое слово).
# 6. Если действие == "взять" -> "Ты берёшь предмет."
#    Если действие == "идти" -> "Ты идёшь."
#    Если действие == "осмотреть" -> "Ты осматриваешься."
#    Иначе -> "Я не понял."

# Напиши код здесь:

command = input("Что делаешь? ").lower().strip()
parts = command.split()
action = parts[0]

if action == "взять":
    print("Ты берёшь предмет.")
elif action == "идти":
    print("Ты идёшь.")
elif action == "осмотреть":
    print("Ты осматриваешься.")
else:
    print("Я не понял.")

# ЗАДАНИЕ 9. Переворот слов в строке
# Дана строка:
text = "Hello World from Python"
# Нужно перевернуть порядок слов, но сами буквы внутри слов оставить как есть.
# Ожидаемый результат: "Python from World Hello"
#
# Подсказка (алгоритм):
# 1. Разбей строку на список слов через .split()
# 2. Переверни список с помощью среза [::-1]
# 3. Собери список обратно в строку через " ".join()
#
# Напиши код здесь:


result = " ".join(text.split()[::-1])
print(result)

# ЗАДАНИЕ 10. Проверка на палиндром
# Палиндром — слово, которое читается одинаково слева направо и справа налево.
# Примеры: "казак", "шалаш", "Анна".
#
# Твоя задача:
# 1. Спроси у пользователя слово через input().
# 2. Приведи его к нижнему регистру и убери лишние пробелы.
# 3. Переверни слово.
# 4. Сравни оригинал и перевернутое слово через if.
# 5. Выведи "Это палиндром!" или "Не палиндром."
#
# Напиши код здесь:

a = input("Слово: ").lower().split()
new = a[::-1]
print(new)

if a == new:
    print('Это палиндром')
else:
    print('Это не палиндром')