# ЗАДАНИЕ 9 (со звёздочкой). Полный цикл работы с инвентарём
# Собери мини-игру:
# 1. Создай пустой инвентарь.
# 2. В цикле спрашивай у пользователя: "подобрать" или "инвентарь" или "выход".
# 3. Если "подобрать" — спроси название предмета и добавь через .append().
# 4. Если "инвентарь" — покажи все предметы через for.
# 5. Если "выход" — выйди из цикла (break).

# Напиши код здесь:


inventory = []

choice = input("подобрать / инвентарь / выход: ").lower().strip()

if choice == "подобрать":
    found = input('Какой предмет?: ').lower().strip()
    inventory.append(found)
    print("Ты подобрал:", found)

elif choice == "инвентарь":
    if len(inventory) == 0:
        print("Рюкзак пуст.")
    else:
        print("В твоём рюкзаке:")
        for item in inventory:
            print(item)
elif choice == "выход":
    pass